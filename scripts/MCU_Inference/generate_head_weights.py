"""
generate_head_weights.py
========================
Extracts the correct classifier head weights (head.1 + head.3) from the
saved PyTorch model and writes them as a C header file (nir_head_weights.h).

This REPLACES the fake SVM/scaler pipeline that was causing systematic Class 5 bias.

Usage:
    python generate_head_weights.py
    python generate_head_weights.py --model "nir_cnn_backbone (1).pt" --out nir_head_weights.h

The correct inference path is:
    CNN backbone -> GAP -> 128-dim features
    -> GELU(head.1 [128->64]) -> head.3 [64->5] -> argmax + 1
"""
import argparse
import torch
import numpy as np
import os

def parse_args():
    p = argparse.ArgumentParser()
    p.add_argument("--model", default="nir_cnn_backbone (1).pt")
    p.add_argument("--out",   default="nir_head_weights.h")
    return p.parse_args()

def quantize_to_int16(arr: np.ndarray):
    """Quantize float array to int16. Returns (int16_array, scale)."""
    amax = np.abs(arr).max()
    if amax == 0:
        return np.zeros(arr.shape, dtype=np.int16), 1.0
    scale = amax / 32767.0
    q = np.round(arr / scale).clip(-32767, 32767).astype(np.int16)
    return q, scale

def write_int16_array(f, name, data, comment=""):
    flat = data.flatten().astype(np.int16)
    n = len(flat)
    if comment:
        f.write(f"/* {comment} */\n")
    f.write(f"const int16_t {name}[{n}] = {{\n")
    ROW = 12
    for i in range(0, n, ROW):
        chunk = flat[i:i+ROW]
        f.write("    " + ", ".join(f"{int(v):6d}" for v in chunk) + ",\n")
    f.write("};\n\n")

def write_float_array(f, name, data, comment=""):
    flat = data.flatten()
    n = len(flat)
    if comment:
        f.write(f"/* {comment} */\n")
    f.write(f"const float {name}[{n}] = {{\n")
    for i, v in enumerate(flat):
        if i % 8 == 0:
            f.write("    ")
        f.write(f"{v:.8f}f")
        if i < n - 1:
            f.write(", ")
        if i % 8 == 7 or i == n - 1:
            f.write("\n")
    f.write("};\n\n")

def main():
    args = parse_args()

    print(f"Loading {args.model} ...")
    model_data = torch.load(args.model, map_location="cpu", weights_only=False)

    if isinstance(model_data, dict) and "cnn_state" in model_data:
        sd = model_data["cnn_state"]
    elif hasattr(model_data, "state_dict"):
        sd = model_data.state_dict()
    else:
        sd = model_data

    # Extract head weights
    h1_w = sd["head.1.weight"].float().numpy()   # [64, 128]
    h1_b = sd["head.1.bias"].float().numpy()     # [64]
    h3_w = sd["head.3.weight"].float().numpy()   # [5, 64]
    h3_b = sd["head.3.bias"].float().numpy()     # [5]

    print("Head weight ranges:")
    for name, arr in [("head.1.weight", h1_w), ("head.1.bias", h1_b),
                      ("head.3.weight", h3_w), ("head.3.bias", h3_b)]:
        amax = np.abs(arr).max()
        ideal_scale = amax / 32767.0
        print(f"  {name:20s}  shape={arr.shape}  abs_max={amax:.6f}  ideal_scale={ideal_scale:.8f}")

    # Quantize
    h1_w_q, h1_w_scale = quantize_to_int16(h1_w)
    h1_b_q, h1_b_scale = quantize_to_int16(h1_b)
    h3_w_q, h3_w_scale = quantize_to_int16(h3_w)
    h3_b_q, h3_b_scale = quantize_to_int16(h3_b)

    print("\nQuantisation scales (copy these into nir_model.h or nir_head_weights.h):")
    print(f"  #define HEAD1_W_SCALE  {h1_w_scale:.8f}f")
    print(f"  #define HEAD1_B_SCALE  {h1_b_scale:.8f}f")
    print(f"  #define HEAD3_W_SCALE  {h3_w_scale:.8f}f")
    print(f"  #define HEAD3_B_SCALE  {h3_b_scale:.8f}f")

    # Verify quantisation error
    print("\nQuantisation verification:")
    for name, orig, qint, scale in [
        ("head.1.weight", h1_w, h1_w_q, h1_w_scale),
        ("head.1.bias",   h1_b, h1_b_q, h1_b_scale),
        ("head.3.weight", h3_w, h3_w_q, h3_w_scale),
        ("head.3.bias",   h3_b, h3_b_q, h3_b_scale),
    ]:
        recon = qint.astype(np.float32) * scale
        err = np.abs(orig - recon).max()
        print(f"  {name:20s}  max_recon_error={err:.6f}")

    with open(args.out, "w") as f:
        f.write("/*\n")
        f.write(" * nir_head_weights.h  -- AUTO-GENERATED by generate_head_weights.py\n")
        f.write(" *\n")
        f.write(" * Replaces the incorrect SVM/scaler weights.\n")
        f.write(" * The correct classifier is a 2-layer linear head:\n")
        f.write(" *   hidden[64] = GELU(head1_W[64x128] @ features[128] + head1_b[64])\n")
        f.write(" *   logits[5]  = head3_W[5x64]   @ hidden[64]  + head3_b[5]\n")
        f.write(" *   pred       = argmax(logits) + 1\n")
        f.write(" *\n")
        f.write(f" * HEAD1_W_SCALE = {h1_w_scale:.8f}f\n")
        f.write(f" * HEAD1_B_SCALE = {h1_b_scale:.8f}f\n")
        f.write(f" * HEAD3_W_SCALE = {h3_w_scale:.8f}f\n")
        f.write(f" * HEAD3_B_SCALE = {h3_b_scale:.8f}f\n")
        f.write(" */\n\n")
        f.write("#ifndef NIR_HEAD_WEIGHTS_H\n")
        f.write("#define NIR_HEAD_WEIGHTS_H\n\n")
        f.write("#include <stdint.h>\n\n")

        f.write(f"#define HEAD1_W_SCALE  {h1_w_scale:.8f}f\n")
        f.write(f"#define HEAD1_B_SCALE  {h1_b_scale:.8f}f\n")
        f.write(f"#define HEAD3_W_SCALE  {h3_w_scale:.8f}f\n")
        f.write(f"#define HEAD3_B_SCALE  {h3_b_scale:.8f}f\n\n")

        write_int16_array(f, "g_head1_weight", h1_w_q,
                          "head.1: Linear(128->64) weights, shape [64][128]")
        write_int16_array(f, "g_head1_bias",   h1_b_q,
                          "head.1: Linear(128->64) bias, shape [64]")
        write_int16_array(f, "g_head3_weight", h3_w_q,
                          "head.3: Linear(64->5) weights, shape [5][64]")
        # head.3 bias: use float to avoid any scale error on tiny 5-element array
        write_float_array(f, "g_head3_bias",   h3_b,
                          "head.3: Linear(64->5) bias float32, shape [5]")

        f.write("#endif /* NIR_HEAD_WEIGHTS_H */\n")

    sz = os.path.getsize(args.out) / 1024
    print(f"\nWritten: {args.out}  ({sz:.1f} KB)")
    print("\nNext steps:")
    print("  1. Copy nir_head_weights.h to your CCS project (MCU_Firmware/)")
    print("  2. Remove nir_weights.c SVM/scaler arrays (g_svm_weights, g_svm_bias,")
    print("     g_scaler_mean, g_scaler_std) -- they are wrong and unused")
    print("  3. Replace run_svm() in nir_inference_main.c with run_head()")
    print("  4. Rebuild and flash")

if __name__ == "__main__":
    main()
