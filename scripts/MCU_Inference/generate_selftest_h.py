"""
generate_selftest_h.py
======================
Extracts 10 samples (2 per class) from the preprocessed SNV CSV and
writes them as a C header for embedding directly into TI firmware.

Usage:
    python generate_selftest_h.py --csv train_preprocessed_snv.csv

Output:
    nir_selftest_data.h  -- drop into your CCS project alongside nir_inference_main.c
"""

import argparse
import numpy as np
import pandas as pd
import struct

NUM_CHANNELS  = 224
SAMPLES_PER_CLASS = 2   # 2 x 5 classes = 10 total

def parse_args():
    p = argparse.ArgumentParser()
    p.add_argument("--csv", required=True)
    p.add_argument("--out", default="nir_selftest_data.h")
    p.add_argument("--samples-per-class", type=int, default=SAMPLES_PER_CLASS)
    return p.parse_args()

def main():
    args = parse_args()

    df = pd.read_csv(args.csv)
    if "class_id" in df.columns:
        y_col  = "class_id"
        x_cols = [c for c in df.columns if c != "class_id"]
    else:
        y_col  = df.columns[0]
        x_cols = list(df.columns[1:])

    assert len(x_cols) == NUM_CHANNELS, \
        f"Expected {NUM_CHANNELS} channels, got {len(x_cols)}"

    # Pick args.samples_per_class rows per class, deterministic
    picked = (df.groupby(y_col, group_keys=False)
                .apply(lambda g: g.sample(
                    min(args.samples_per_class, len(g)), random_state=0),
                    include_groups=False)
              )
    # Re-attach the label column lost by include_groups=False
    picked.insert(0, y_col, df.loc[picked.index, y_col].values)
    picked = picked.reset_index(drop=True)

    X = picked[x_cols].values.astype(np.float32)
    y = picked[y_col].values.astype(np.int32)
    N = len(X)

    print(f"Extracted {N} samples:")
    for cls in sorted(np.unique(y)):
        print(f"  class {cls}: {np.sum(y == cls)} samples")

    with open(args.out, "w") as f:
        f.write("/*\n")
        f.write(" * nir_selftest_data.h  -- AUTO-GENERATED by generate_selftest_h.py\n")
        f.write(f" * {N} samples ({args.samples_per_class} per class), {NUM_CHANNELS} float32 channels each\n")
        f.write(" * Drop into CCS project alongside nir_inference_main.c\n")
        f.write(" */\n\n")
        f.write("#ifndef NIR_SELFTEST_DATA_H\n")
        f.write("#define NIR_SELFTEST_DATA_H\n\n")
        f.write(f"#define SELFTEST_N_SAMPLES   {N}u\n")
        f.write(f"#define SELFTEST_N_CHANNELS  {NUM_CHANNELS}u\n\n")

        # True labels array
        f.write("/* True class labels (1-5) */\n")
        f.write(f"static const uint8_t g_selftest_labels[{N}] = {{\n    ")
        f.write(", ".join(str(int(v)) for v in y))
        f.write("\n};\n\n")

        # Sample data: one float array per sample for readability
        f.write("/* Input samples: g_selftest_X[sample][channel] float32 */\n")
        f.write(f"static const float g_selftest_X[{N}][{NUM_CHANNELS}] = {{\n")
        for i in range(N):
            f.write(f"    /* sample {i}  true_class={int(y[i])} */\n")
            f.write("    {\n        ")
            vals = [f"{v:.8f}f" for v in X[i]]
            # 4 values per line
            for j, v in enumerate(vals):
                f.write(v)
                if j < len(vals) - 1:
                    f.write(", ")
                if (j + 1) % 4 == 0 and j < len(vals) - 1:
                    f.write("\n        ")
            f.write("\n    }")
            if i < N - 1:
                f.write(",")
            f.write("\n")
        f.write("};\n\n")
        f.write("#endif /* NIR_SELFTEST_DATA_H */\n")

    import os
    size_kb = os.path.getsize(args.out) / 1024
    print(f"\nWritten: {args.out}  ({size_kb:.1f} KB)")
    print("Next: copy nir_selftest_data.h into your CCS project folder")

if __name__ == "__main__":
    main()