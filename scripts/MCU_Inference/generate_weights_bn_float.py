"""
generate_weights_bn_float.py
============================
Regenerates ONLY the BatchNorm parameter arrays as raw float32.
Drop the output nir_bn_weights.h into your CCS project.
The large conv weights (g_bb0, g_bb3, g_bb7) stay quantized in nir_weights.c.

Usage:
    python generate_weights_bn_float.py --model nir_model.pt
    python generate_weights_bn_float.py --model nir_cnn_backbone(1).pt --out nir_bn_weights.h

Requires: torch
"""

import argparse
import torch
import torch.nn as nn

def parse_args():
    p = argparse.ArgumentParser()
    p.add_argument("--model", required=True, help="Path to saved PyTorch model (.pt)")
    p.add_argument("--out",   default="nir_bn_weights.h")
    return p.parse_args()

def fmt_float(v):
    """Format float for C — always has decimal point and f suffix."""
    s = f"{v:.8f}f"
    return s

def write_float_array(f, name, data, comment=""):
    n = len(data)
    if comment:
        f.write(f"/* {comment} */\n")
    f.write(f"const float {name}[{n}] = {{\n")
    for i, v in enumerate(data):
        if i % 8 == 0:
            f.write("    ")
        f.write(fmt_float(v))
        if i < n - 1:
            f.write(", ")
        if i % 8 == 7 or i == n - 1:
            f.write("\n")
    f.write("};\n\n")

def main():
    args = parse_args()

    model = torch.load(args.model, map_location="cpu", weights_only=False)
    if hasattr(model, "eval"):
        model.eval()

    # Navigate to state dict
    sd = model.state_dict() if hasattr(model, "state_dict") else model
    if "cnn_state" in sd:
        sd = sd["cnn_state"]

    # Print all keys so user can verify layer names
    print("Model state dict keys (BN-related):")
    for k in sd.keys():
        if any(x in k for x in ["running_mean","running_var","bn","norm",
                                  "backbone.1","backbone.4","backbone.8"]):
            v = sd[k]
            print(f"  {k:50s}  shape={list(v.shape)}  "
                  f"min={v.min():.4f}  max={v.max():.4f}")
    print()

    # Extract BN arrays — adjust key names if your model uses different naming
    def get(key):
        if key in sd:
            return sd[key].float().numpy().tolist()
        # Try common alternate naming patterns
        for alt in [key.replace("backbone","model.backbone"),
                    key.replace("backbone","net.backbone")]:
            if alt in sd:
                return sd[alt].float().numpy().tolist()
        raise KeyError(f"Key not found: {key}\nAvailable: {list(sd.keys())}")

    try:
        bb1_w   = get("backbone.1.weight")
        bb1_b   = get("backbone.1.bias")
        bb1_mu  = get("backbone.1.running_mean")
        bb1_var = get("backbone.1.running_var")

        bb4_w   = get("backbone.4.weight")
        bb4_b   = get("backbone.4.bias")
        bb4_mu  = get("backbone.4.running_mean")
        bb4_var = get("backbone.4.running_var")

        bb8_w   = get("backbone.8.weight")
        bb8_b   = get("backbone.8.bias")
        bb8_mu  = get("backbone.8.running_mean")
        bb8_var = get("backbone.8.running_var")
    except KeyError as e:
        print(f"[ERROR] {e}")
        print("Edit the key names in this script to match your model's state dict.")
        return

    # Validate ranges
    print("BN parameter ranges (should be reasonable):")
    for name, arr in [
        ("bb1.weight(gamma)", bb1_w), ("bb1.bias(beta)", bb1_b),
        ("bb1.running_mean",  bb1_mu), ("bb1.running_var", bb1_var),
        ("bb4.weight",  bb4_w), ("bb4.bias",  bb4_b),
        ("bb4.mean",    bb4_mu), ("bb4.var",   bb4_var),
        ("bb8.weight",  bb8_w), ("bb8.bias",  bb8_b),
        ("bb8.mean",    bb8_mu), ("bb8.var",   bb8_var),
    ]:
        mn, mx = min(arr), max(arr)
        print(f"  {name:30s}  [{mn:.4f}, {mx:.4f}]")

    # Also extract SVM/scaler if they exist as float in model
    # (optional -- only if your model stores them)
    svm_w = svm_b = scaler_mu = scaler_std = None
    for key in ["svm.coef_", "classifier.weight", "head.3.weight"]:
        if key in sd:
            svm_w = sd[key].float().numpy().flatten().tolist()
            break
    for key in ["svm.intercept_", "classifier.bias", "head.3.bias"]:
        if key in sd:
            svm_b = sd[key].float().numpy().flatten().tolist()
            break

    with open(args.out, "w") as f:
        f.write("/*\n")
        f.write(f" * nir_bn_weights.h  -- AUTO-GENERATED by generate_weights_bn_float.py\n")
        f.write(" * BatchNorm parameters stored as raw float32 (no quantization).\n")
        f.write(" * This replaces the int16 BN arrays in nir_weights.c/.h.\n")
        f.write(" * Fixes the running_mean scale underflow bug (bb1 mean was 70x too small).\n")
        f.write(" */\n\n")
        f.write("#ifndef NIR_BN_WEIGHTS_H\n")
        f.write("#define NIR_BN_WEIGHTS_H\n\n")

        write_float_array(f, "g_bn1_weight",       bb1_w,  "backbone.1 BN gamma (64ch)")
        write_float_array(f, "g_bn1_bias",         bb1_b,  "backbone.1 BN beta  (64ch)")
        write_float_array(f, "g_bn1_running_mean", bb1_mu, "backbone.1 BN running_mean (64ch)")
        write_float_array(f, "g_bn1_running_var",  bb1_var,"backbone.1 BN running_var  (64ch)")

        write_float_array(f, "g_bn4_weight",       bb4_w,  "backbone.4 BN gamma (128ch)")
        write_float_array(f, "g_bn4_bias",         bb4_b,  "backbone.4 BN beta  (128ch)")
        write_float_array(f, "g_bn4_running_mean", bb4_mu, "backbone.4 BN running_mean (128ch)")
        write_float_array(f, "g_bn4_running_var",  bb4_var,"backbone.4 BN running_var  (128ch)")

        write_float_array(f, "g_bn8_weight",       bb8_w,  "backbone.8 BN gamma (128ch)")
        write_float_array(f, "g_bn8_bias",         bb8_b,  "backbone.8 BN beta  (128ch)")
        write_float_array(f, "g_bn8_running_mean", bb8_mu, "backbone.8 BN running_mean (128ch)")
        write_float_array(f, "g_bn8_running_var",  bb8_var,"backbone.8 BN running_var  (128ch)")

        f.write("#endif /* NIR_BN_WEIGHTS_H */\n")

    import os
    sz = os.path.getsize(args.out) / 1024
    print(f"\nWritten: {args.out}  ({sz:.1f} KB)")
    print("Next: add nir_bn_weights.h to CCS project, update nir_inference_main.c")

if __name__ == "__main__":
    main()